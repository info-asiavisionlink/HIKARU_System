export const STORE_ANALYSIS_PROMPT = (
  storeName: string,
  data: string
) => `
以下は「${storeName}」の清掃品質データです。分析して改善提案を日本語で生成してください。

【データ】
${data}

【分析要件】
- 品質スコアのトレンドを分析する
- 問題が多い場所・項目を特定する
- 具体的な改善提案を3点以内で提示する
- 前向きかつ建設的なトーンで記述する

JSON形式で回答：
{
  "trend": "improving | declining | stable",
  "issues": ["問題点1", "問題点2"],
  "suggestions": ["改善提案1", "改善提案2", "改善提案3"],
  "summary": "総合コメント（2〜3文）"
}
`.trim()

